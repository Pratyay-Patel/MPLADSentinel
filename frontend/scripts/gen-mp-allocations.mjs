/**
 * Generates `src/data/mpAllocations.ts` from the official MoSPI eSAKSHI
 * per-MP allocation tables in `docs/data/`.
 *
 *   node scripts/gen-mp-allocations.mjs   (run from the frontend/ directory)
 *
 * The CSVs are static (a periodic manual download from
 * mplads.mospi.gov.in/digigov/dashboard.html → "Allocated Limit for Hon'ble
 * MPs"), so this is a dev-time step, not part of the build. Commit the output.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const DOCS = path.resolve(here, '../../docs/data');
const OUT = path.resolve(here, '../src/data/mpAllocations.ts');

// --- CSV parse (quoted fields, embedded commas, BOM) -----------------
function parseCsv(text) {
  text = text.replace(/^﻿/, '');
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (c !== '\r') field += c;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.length > 1);
}

// --- normalisation (kept identical to the emitted TS below) ----------
const HONORIFICS = new Set(['DR', 'SHRI', 'SMT', 'KM', 'KUMARI', 'ADV', 'PROF', 'ER', 'SARDAR', 'JUSTICE']);
function normalizeMpName(name) {
  const cleaned = (name ?? '')
    .toUpperCase()
    .replace(/\(\s*\d{4}\s*-\s*\d{2,4}\s*\)/g, ' ')
    .replace(/ALIAS|@/g, ' ')
    .replace(/[^A-Z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const toks = cleaned.split(' ');
  while (toks.length > 1 && HONORIFICS.has(toks[0])) toks.shift();
  return toks.join(' ');
}
function normalizeState(s) {
  return (s ?? '')
    .toUpperCase()
    .replace(/[^A-Z]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
const money = (s) => Number(String(s).replace(/[",\s₹]/g, '')) || 0;

function load(file, house) {
  const rows = parseCsv(fs.readFileSync(path.join(DOCS, file), 'utf8'));
  const out = [];
  for (const r of rows.slice(1)) {
    if (/grand total/i.test(r[0]) || !r[2] || !r[2].trim()) continue;
    const allocated = money(r[4]);
    if (allocated <= 0) continue;
    out.push({ key: normalizeMpName(r[2]), allocated, house, state: normalizeState(r[1]) });
  }
  return out;
}

const entries = [
  ...load('mp-allocation-lok-sabha.csv', 'LOK_SABHA'),
  ...load('mp-allocation-rajya-sabha.csv', 'RAJYA_SABHA'),
];

const byKey = new Map();
for (const e of entries) {
  if (!byKey.has(e.key)) byKey.set(e.key, []);
  byKey.get(e.key).push({ allocated: e.allocated, house: e.house, state: e.state });
}

const sortedKeys = [...byKey.keys()].sort();
const body = sortedKeys
  .map((k) => {
    const list = byKey
      .get(k)
      .map((v) => `{ allocated: ${v.allocated}, house: '${v.house}', state: ${JSON.stringify(v.state)} }`)
      .join(', ');
    return `  ${JSON.stringify(k)}: [${list}],`;
  })
  .join('\n');

const collisions = sortedKeys.filter((k) => byKey.get(k).length > 1);

const ts = `/**
 * AUTO-GENERATED by scripts/gen-mp-allocations.mjs — do not edit by hand.
 *
 * Official per-MP MPLADS allocated limit, from the MoSPI eSAKSHI dashboard
 * (docs/data/mp-allocation-{lok,rajya}-sabha.csv). ${entries.length} MPs
 * (${entries.length - collisions.length} unique normalised names;
 * ${collisions.length} name collisions resolved by state at lookup).
 */

export type House = 'LOK_SABHA' | 'RAJYA_SABHA';

export interface MpAllocation {
  /** MPLADS allocated limit, in rupees. */
  allocated: number;
  house: House;
  /** Normalised state — only used to disambiguate two MPs with the same name. */
  state: string;
}

const HONORIFICS = new Set([
  'DR', 'SHRI', 'SMT', 'KM', 'KUMARI', 'ADV', 'PROF', 'ER', 'SARDAR', 'JUSTICE',
]);

/**
 * Normalise an MP name for cross-source matching. Uppercase, drop \`(2022-28)\`
 * term suffixes and leading honorifics, reduce punctuation to single spaces.
 * Used both here (keys) and by the join in \`mpComparison.ts\`.
 */
export function normalizeMpName(name: string): string {
  const cleaned = (name ?? '')
    .toUpperCase()
    .replace(/\\(\\s*\\d{4}\\s*-\\s*\\d{2,4}\\s*\\)/g, ' ')
    .replace(/ALIAS|@/g, ' ')
    .replace(/[^A-Z0-9]+/g, ' ')
    .replace(/\\s+/g, ' ')
    .trim();
  const toks = cleaned.split(' ');
  while (toks.length > 1 && HONORIFICS.has(toks[0])) toks.shift();
  return toks.join(' ');
}

export function normalizeState(state: string | null | undefined): string {
  return (state ?? '')
    .toUpperCase()
    .replace(/[^A-Z]+/g, ' ')
    .replace(/\\s+/g, ' ')
    .trim();
}

/** Normalised MP name → allocation(s). An array of >1 only for same-name MPs. */
export const MP_ALLOCATIONS: Record<string, MpAllocation[]> = {
${body}
};

/**
 * Look up an MP's official allocation by name, using state to break same-name
 * ties. \`null\` when the MP is not on the official list (or a tie can't be
 * resolved) — callers must show "unavailable", never a guess.
 */
export function lookupAllocation(name: string, state: string | null): MpAllocation | null {
  const entries = MP_ALLOCATIONS[normalizeMpName(name)];
  if (!entries || entries.length === 0) return null;
  if (entries.length === 1) return entries[0];
  const ns = normalizeState(state);
  const byState = entries.filter((e) => e.state === ns);
  return byState.length === 1 ? byState[0] : null;
}
`;

fs.writeFileSync(OUT, ts);
console.log(
  `wrote ${path.relative(process.cwd(), OUT)} — ${entries.length} MPs, ${sortedKeys.length} keys, ${collisions.length} collisions: ${collisions.join(', ')}`,
);
